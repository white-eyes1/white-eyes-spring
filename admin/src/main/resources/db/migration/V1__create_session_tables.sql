-- Spring Session JDBC 세션 테이블: 앱마다 따로 (overview.md '세션')

CREATE TABLE SPRING_SESSION_USER (
    PRIMARY_ID CHAR(36) NOT NULL,
    SESSION_ID CHAR(36) NOT NULL,
    CREATION_TIME BIGINT NOT NULL,
    LAST_ACCESS_TIME BIGINT NOT NULL,
    MAX_INACTIVE_INTERVAL INT NOT NULL,
    EXPIRY_TIME BIGINT NOT NULL,
    PRINCIPAL_NAME VARCHAR(100),
    CONSTRAINT SPRING_SESSION_USER_PK PRIMARY KEY (PRIMARY_ID)
) ENGINE = InnoDB;

CREATE UNIQUE INDEX SPRING_SESSION_USER_IX1 ON SPRING_SESSION_USER (SESSION_ID);
CREATE INDEX SPRING_SESSION_USER_IX2 ON SPRING_SESSION_USER (EXPIRY_TIME);
CREATE INDEX SPRING_SESSION_USER_IX3 ON SPRING_SESSION_USER (PRINCIPAL_NAME);

CREATE TABLE SPRING_SESSION_USER_ATTRIBUTES (
    SESSION_PRIMARY_ID CHAR(36) NOT NULL,
    ATTRIBUTE_NAME VARCHAR(200) NOT NULL,
    ATTRIBUTE_BYTES BLOB NOT NULL,
    CONSTRAINT SPRING_SESSION_USER_ATTRIBUTES_PK PRIMARY KEY (SESSION_PRIMARY_ID, ATTRIBUTE_NAME),
    CONSTRAINT SPRING_SESSION_USER_ATTRIBUTES_FK FOREIGN KEY (SESSION_PRIMARY_ID) REFERENCES SPRING_SESSION_USER (PRIMARY_ID) ON DELETE CASCADE
) ENGINE = InnoDB;

CREATE TABLE SPRING_SESSION_ADMIN (
    PRIMARY_ID CHAR(36) NOT NULL,
    SESSION_ID CHAR(36) NOT NULL,
    CREATION_TIME BIGINT NOT NULL,
    LAST_ACCESS_TIME BIGINT NOT NULL,
    MAX_INACTIVE_INTERVAL INT NOT NULL,
    EXPIRY_TIME BIGINT NOT NULL,
    PRINCIPAL_NAME VARCHAR(100),
    CONSTRAINT SPRING_SESSION_ADMIN_PK PRIMARY KEY (PRIMARY_ID)
) ENGINE = InnoDB;

CREATE UNIQUE INDEX SPRING_SESSION_ADMIN_IX1 ON SPRING_SESSION_ADMIN (SESSION_ID);
CREATE INDEX SPRING_SESSION_ADMIN_IX2 ON SPRING_SESSION_ADMIN (EXPIRY_TIME);
CREATE INDEX SPRING_SESSION_ADMIN_IX3 ON SPRING_SESSION_ADMIN (PRINCIPAL_NAME);

CREATE TABLE SPRING_SESSION_ADMIN_ATTRIBUTES (
    SESSION_PRIMARY_ID CHAR(36) NOT NULL,
    ATTRIBUTE_NAME VARCHAR(200) NOT NULL,
    ATTRIBUTE_BYTES BLOB NOT NULL,
    CONSTRAINT SPRING_SESSION_ADMIN_ATTRIBUTES_PK PRIMARY KEY (SESSION_PRIMARY_ID, ATTRIBUTE_NAME),
    CONSTRAINT SPRING_SESSION_ADMIN_ATTRIBUTES_FK FOREIGN KEY (SESSION_PRIMARY_ID) REFERENCES SPRING_SESSION_ADMIN (PRIMARY_ID) ON DELETE CASCADE
) ENGINE = InnoDB;
